import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { colors, fontStack, layout, motion, radius, type } from '../lib/design/tokens'

const vars = (mode: 'light' | 'dark') =>
  Object.entries(colors[mode]).map(([k, v]) => `  --${k}: ${v};`).join('\n')

const typeVars = Object.entries(type).map(([k, [size, lh, w, ls]]) =>
  `  --t-${k}-size: ${size}px;\n  --t-${k}-lh: ${lh}px;\n  --t-${k}-weight: ${w};\n  --t-${k}-ls: ${ls}em;`).join('\n')

const typeUtils = Object.keys(type).map((k) => `.t-${k} {
  font-size: var(--t-${k}-size);
  line-height: var(--t-${k}-lh);
  font-weight: var(--t-${k}-weight);
  letter-spacing: var(--t-${k}-ls);${k === 'caption' ? '\n  text-transform: uppercase;' : ''}${['metric', 'largeTitle'].includes(k) ? '\n  font-variant-numeric: tabular-nums;' : ''}
}`).join('\n')

const css = `/* GENERATED by scripts/gen-tokens.ts from lib/design/tokens.ts — do not edit. */
:root {
${vars('light')}
  --font-sans: ${fontStack.sans};
  --font-mono: ${fontStack.mono};
${typeVars}
  --radius-sm: ${radius.sm}px;
  --radius-md: ${radius.md}px;
  --radius-lg: ${radius.lg}px;
  --radius-xl: ${radius.xl}px;
  --ease: ${motion.easing};
  --dur-fast: ${motion.fast}ms;
  --dur-base: ${motion.base}ms;
  --dur-slow: ${motion.slow}ms;
  --sidebar-w: ${layout.sidebar}px;
  --sidebar-w-collapsed: ${layout.sidebarCollapsed}px;
  --inspector-w: ${layout.inspector}px;
  --max-content: ${layout.maxContent}px;
  --toolbar-h: ${layout.toolbar}px;
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${vars('dark').replace(/^/gm, '  ')}
    color-scheme: dark;
  }
}
:root[data-theme='dark'] {
${vars('dark')}
  color-scheme: dark;
}
@media (prefers-reduced-transparency: reduce) {
  :root, :root[data-theme='dark'] {
    --material-sidebar: var(--material-solid);
    --material-toolbar: var(--material-solid);
  }
}
${typeUtils}
`
writeFileSync(path.join(__dirname, '../app/tokens.css'), css)
console.log('wrote app/tokens.css')
